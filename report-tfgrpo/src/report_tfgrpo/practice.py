"""Training-Free GRPO on report pages: learn an experience list for the page agent.

    PYTHONPATH=src:../report-gepa/src ../report-gepa/.venv/bin/python -m report_tfgrpo.practice runs/<name> [--group 3] [--batch 4]

Follows the official implementation (TencentCloudADP/youtu-agent, utu/practice/):
for every batch of stories, each story gets --group pages written with the base
guide plus the current experience list; every page gets a reward; an LLM
summarises each page, compares the pages of one story to extract at most
--per-story experiences (the semantic group advantage), turns each story's
experiences into ADD/UPDATE/DELETE/NONE operations on the list (group update),
and merges the batch's operations into one revision of the list (batch update).
There is no acceptance test: the revised list is used for the next batch.

Reward of a page, with report-gepa's judge (deepseek) and rubric:
- trust: 1.1 from the capture and 1.3 by eye; a violation makes the reward 0.
  1.2 (the agent fact check) is left out.
- expression: every scored 2.x item, 0-1, in one call per page.
- aesthetics: 3.1 and 3.2 by group pick among the story's pages, in a Latin
  square (three pages, three rounds); a page's net share of votes in [-1, 1]
  maps to [0, 1].
The reward is the mean of those items (equal weights). Only who is better within
a story matters to the method, not how rewards compare across stories.

Pages, captures and judgements are generated by report-gepa (generate_page,
capture, judge) and kept under <run>/step-NN/<story>/page-K/; the experience list
after every step is <run>/experiences/step-NN.json. A restarted run reuses what
is on disk and continues from the last finished step.
"""

from __future__ import annotations

import argparse
import json
import random
import re
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from report_gepa import judge as J
from report_gepa.capture import capture
from report_gepa.generate import GUIDES, generate_page
from report_gepa.llm import LLM
from report_gepa.optimize import DATA, TASK, split, stories
from report_gepa.rubric import load

from . import prompts as P

MODEL = "deepseek-v4.1-flash"  # writes the pages, judges them, and runs the four learning steps
SUMMARY_FRAMES = 12  # frames shown to the summariser per page, sampled evenly
MAX_TOKENS = 32768


def ask(system: str, user: str | list[dict]) -> str:
    r = LLM(MODEL).chat([{"role": "system", "content": system}, {"role": "user", "content": user}], max_tokens=MAX_TOKENS)
    return r.text


def json_array(text: str) -> list[dict]:
    body = text.split("```json")[-1].split("```")[0]
    ops = json.loads(body)
    return [op for op in ops if isinstance(op, dict)]


def format_experiences(exps: dict[str, str]) -> str:
    return "\n".join(f"[{i}]. {e}" for i, e in exps.items()) if exps else "None"


class Practice:
    def __init__(self, run: Path, guide: Path, group: int, per_story: int, workers: int, browsers: int):
        self.run = run
        self.guide = guide.read_text(encoding="utf-8")
        self.group = group
        self.per_story = per_story
        self.workers = workers
        self.browsers = threading.Semaphore(browsers)
        self.rubric = load()
        self.scored = [it for it in self.rubric.values() if it.scored]
        self.pick_items = [it for it in self.rubric.values() if it.pairwise]
        self.meta = {r["id"]: r for r in stories()}
        rubric_text = "\n".join(f"- {it.id} {it.name}:{it.description}" for it in self.rubric.values() if it.id != "1.2")
        objectives = {"agent_objective": P.AGENT_OBJECTIVE, "learning_objective": P.LEARNING_OBJECTIVE.format(rubric=rubric_text)}
        self.sp = {
            "summary": P.SINGLE_SUMMARY_SP.format(**objectives),
            "advantage": P.GROUP_ADVANTAGE_SP.format(**objectives, num_experiences=per_story),
            "group": P.GROUP_UPDATE_SP.format(**objectives),
            "batch": P.BATCH_UPDATE_SP.format(**objectives),
        }
        self.task = run / "task.txt"
        self.task.write_text(TASK, encoding="utf-8")

    # rollouts

    def system_prompt(self, exps: dict[str, str]) -> str:
        return self.guide + (P.EXPERIENCE_HEADER + format_experiences(exps) if exps else "")

    def page(self, step_dir: Path, story: str, k: int, guide_path: Path) -> Path | None:
        """Write and capture page k of a story; its evidence dir, or None if no page was delivered."""
        base = step_dir / story
        record = base / f"page-{k}" / "record.json"
        rec = (json.loads(record.read_text(encoding="utf-8")) if record.exists() else
               generate_page(guide_path, [DATA / story], base, f"page-{k}", MODEL, render_slots=self.browsers, task_path=self.task))
        if not rec["delivered"]:
            print(f"[page] {step_dir.name}/{story}/page-{k}: not delivered ({rec.get('detail')})", flush=True)
            return None
        ev = base / f"ev-{k}"
        if not (ev / "evidence.json").exists():
            with self.browsers:
                capture(str(base / f"page-{k}" / "index.html"), ev, None, [DATA / story])
        return ev

    def judge_story(self, step_dir: Path, story: str, evs: list[Path]) -> dict[str, dict]:
        """Judgements per page (keyed by evidence dir name), reusing judgements.json."""
        path = step_dir / story / "judgements.json"
        out = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        for ev in evs:
            items = out.setdefault(ev.name, {})
            gate = J.gate(ev)
            items["1.1"] = {"violated": gate["violated"], "reason": "; ".join(gate["problems"])}
            for name, fn, ids in (("1.3", lambda: {"1.3": J.check(self.rubric["1.3"], ev, MODEL)}, ["1.3"]),
                                  ("2.x", lambda: J.page_group(self.scored, ev, MODEL)[1], [it.id for it in self.scored])):
                if all(i in items for i in ids):
                    continue
                try:
                    items.update(fn())
                except Exception as e:  # noqa: BLE001 - a failed judgement leaves the items out, it is not a 0
                    print(f"[judge] {step_dir.name}/{story}/{ev.name} {name}: FAILED {str(e)[:200]}", flush=True)
        if len(evs) >= 2 and "pick" not in out:
            try:
                out["pick"] = J.pick(self.pick_items, evs, MODEL)[1]
            except Exception as e:  # noqa: BLE001
                print(f"[judge] {step_dir.name}/{story} pick: FAILED {str(e)[:200]}", flush=True)
        path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
        return out

    def reward(self, items: dict, pick: dict, name: str) -> tuple[float, list[str]]:
        """A page's reward and the critique lines the summariser reads."""
        lines, parts = [], {}
        vetoed = [k for k in ("1.1", "1.3") if items.get(k, {}).get("violated") is True]
        for k in vetoed:
            r = items[k]
            lines.append(f"{k} {self.rubric[k].name}:犯了,整页 0 分。{r.get('where') or ''} {r.get('reason') or ''}".strip())
        for it in self.scored:
            r = items.get(it.id)
            if r and r.get("score") is not None:
                parts[it.id] = r["score"]
                lines.append(f"{it.id} {it.name}:{r['score']:.2f}。{r.get('where') or ''} {r.get('reason') or ''}".strip())
        for it in self.pick_items:
            r = pick.get(it.id)
            if r and r.get("ok"):
                net = r["pick_norm"][name]
                parts[it.id] = (net + 1) / 2
                verdict = "比同组其他页面明显好" if net > 0 else "比同组其他页面明显差" if net < 0 else "和同组其他页面没有明显差别"
                lines.append(f"{it.id} {it.name}(同一份数据的几个页面组内比较):{verdict}")
        reward = 0.0 if vetoed else (sum(parts.values()) / len(parts) if parts else 0.0)
        return reward, lines

    # the four learning steps

    def summarise(self, story: str, ev: Path, critique: list[str]) -> str:
        saved = J.MAX_FRAMES
        J.MAX_FRAMES = SUMMARY_FRAMES
        try:
            parts = J.evidence_parts(ev, "")
        finally:
            J.MAX_FRAMES = saved
        user = [{"type": "text", "text": P.SINGLE_SUMMARY_UP.format(question=self.question(story), critique="\n".join(critique))}] + parts
        return ask(self.sp["summary"], user)

    def question(self, story: str) -> str:
        m = self.meta[story]
        files = ", ".join(m["files"][:12]) + (f" 等 {len(m['files'])} 个文件" if len(m["files"]) > 12 else "")
        return f"The Pudding 公开的数据「{m['title']}」,文件:{files}"

    def advantage(self, story: str, rollouts: list[dict]) -> str:
        trajectories = "\n\n".join(f"尝试 {i + 1}(reward {r['reward']:.2f}):\n{r['summary']}" for i, r in enumerate(rollouts))
        text = ask(self.sp["advantage"], P.GROUP_ADVANTAGE_UP.format(question=self.question(story), trajectories=trajectories))
        m = re.search(r"<Experiences>\s*(.*?)\s*</Experiences>", text, re.S | re.I)
        return m.group(1).strip() if m else ""

    def group_update(self, exps: dict[str, str], new: str) -> list[dict]:
        text = ask(self.sp["group"], P.GROUP_UPDATE_UP.format(existing=format_experiences(exps), new=new))
        return json_array(text)

    def batch_update(self, exps: dict[str, str], ops: list[dict]) -> dict[str, str]:
        if not ops:
            return dict(exps)
        blocks = []
        for i, e in exps.items():
            related = [op for op in ops if str(op.get("id")) == i]
            block = f"经验 {i}:\n内容:{e}\n"
            block += ("相关操作:\n" + "\n".join(json.dumps(op, ensure_ascii=False) for op in related)) if related else "没有相关操作。"
            blocks.append(block)
        loose = [op for op in ops if not op.get("id")]
        if loose:
            blocks.append("不针对现有经验的操作:\n" + "\n".join(json.dumps(op, ensure_ascii=False) for op in loose))
        plan = []
        for _ in range(3):
            try:
                plan = json_array(ask(self.sp["batch"], P.BATCH_UPDATE_UP.format(experiences_and_operations="\n\n".join(blocks))))
                break
            except Exception as e:  # noqa: BLE001 - the official code retries a plan that does not parse
                print(f"[batch update] could not read the plan: {str(e)[:120]}", flush=True)
        new = dict(exps)
        next_id = max([int(i) for i in new] + [-1]) + 1
        for op in plan:
            kind, content, target = op.get("operation", "ADD"), op.get("content", ""), str(op.get("id")) if op.get("id") is not None else None
            if not content:
                continue
            if kind == "ADD" or (kind == "UPDATE" and target not in new):
                new[str(next_id)] = content
                next_id += 1
            elif kind == "UPDATE":
                new[target] = content
            elif kind == "DELETE" and target in new:
                del new[target]
        return new

    # one step

    def step(self, n: int, batch: list[str], exps: dict[str, str]) -> dict[str, str]:
        step_dir = self.run / f"step-{n:02d}"
        step_dir.mkdir(parents=True, exist_ok=True)
        guide_path = step_dir / "system.md"
        if not guide_path.exists():
            guide_path.write_text(self.system_prompt(exps), encoding="utf-8")
        print(f"== step {n}: {' '.join(batch)} ({len(exps)} experiences)", flush=True)

        with ThreadPoolExecutor(self.workers) as pool:
            futures = {(s, k): pool.submit(self.page, step_dir, s, k, guide_path) for s in batch for k in range(1, self.group + 1)}
            evs = {s: [ev for k in range(1, self.group + 1) if (ev := futures[(s, k)].result())] for s in batch}

        def per_story(story: str) -> dict:
            judged = self.judge_story(step_dir, story, evs[story])
            rollouts = []
            for ev in evs[story]:
                reward, critique = self.reward(judged.get(ev.name, {}), judged.get("pick", {}), ev.name)
                cache = step_dir / story / f"summary-{ev.name}.md"
                if not cache.exists():
                    cache.write_text(self.summarise(story, ev, critique), encoding="utf-8")
                rollouts.append({"page": ev.name, "reward": reward, "summary": cache.read_text(encoding="utf-8")})
            print(f"[rewards] {step_dir.name}/{story}: " + " ".join(f"{r['page']}={r['reward']:.3f}" for r in rollouts), flush=True)
            if len(rollouts) < 2:
                return {"story": story, "rollouts": rollouts, "experiences": "", "operations": []}
            adv = step_dir / story / "advantage.md"
            if not adv.exists():
                adv.write_text(self.advantage(story, rollouts), encoding="utf-8")
            new = adv.read_text(encoding="utf-8")
            ops_path = step_dir / story / "operations.json"
            if not ops_path.exists() and new:
                ops_path.write_text(json.dumps(self.group_update(exps, new), ensure_ascii=False, indent=1), encoding="utf-8")
            ops = json.loads(ops_path.read_text(encoding="utf-8")) if ops_path.exists() else []
            return {"story": story, "rollouts": rollouts, "experiences": new, "operations": ops}

        with ThreadPoolExecutor(len(batch)) as pool:
            results = list(pool.map(per_story, batch))
        (step_dir / "rollouts.json").write_text(json.dumps(results, ensure_ascii=False, indent=1), encoding="utf-8")

        ops = [op for r in results for op in r["operations"] if op.get("operation") != "NONE"]
        new = self.batch_update(exps, ops)
        print(f"[step {n}] {len(ops)} operations -> {len(new)} experiences", flush=True)
        return new


def save(run: Path, n: int, exps: dict[str, str]) -> None:
    d = run / "experiences"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"step-{n:02d}.json").write_text(json.dumps(exps, ensure_ascii=False, indent=1), encoding="utf-8")
    (d / f"step-{n:02d}.md").write_text(format_experiences(exps) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run", type=Path)
    ap.add_argument("--guide", type=Path, default=GUIDES / "seed.md", help="base system prompt; experiences go after it")
    ap.add_argument("--group", type=int, default=3, help="pages per story (the official grpo_n)")
    ap.add_argument("--batch", type=int, default=4, help="stories per step")
    ap.add_argument("--per-story", type=int, default=2, help="experiences extracted per story at most")
    ap.add_argument("--epochs", type=int, default=1)
    ap.add_argument("--steps", type=int, help="stop after this many steps")
    ap.add_argument("--stories", help="comma-separated story ids instead of the train split")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--workers", type=int, default=8, help="pages written at the same time")
    ap.add_argument("--browsers", type=int, default=4)
    args = ap.parse_args()

    args.run.mkdir(parents=True, exist_ok=True)
    train = args.stories.split(",") if args.stories else split(8, 19, 0)[0]
    practice = Practice(args.run, args.guide, args.group, args.per_story, args.workers, args.browsers)
    order = []
    for epoch in range(args.epochs):
        ids = list(train)
        random.Random(args.seed + epoch).shuffle(ids)
        order += [ids[i:i + args.batch] for i in range(0, len(ids) - args.batch + 1, args.batch)]
    if args.steps:
        order = order[:args.steps]

    exps: dict[str, str] = {}
    for n, batch in enumerate(order):
        done = args.run / "experiences" / f"step-{n:02d}.json"
        if done.exists():
            exps = json.loads(done.read_text(encoding="utf-8"))
            continue
        exps = practice.step(n, batch, exps)
        save(args.run, n, exps)
    print(f"done: {len(order)} steps, {len(exps)} experiences in {args.run}/experiences/", flush=True)


if __name__ == "__main__":
    main()
