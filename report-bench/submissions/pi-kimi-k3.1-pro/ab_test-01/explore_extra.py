import pandas as pd, numpy as np
D=pd.read_csv('data/data.csv')
D['arm']=D.group.str.strip().map({'对照组':'Control','实验组':'Treatment'})
D['dept']=D.department.map({'内科':'Internal medicine','儿科':'Pediatrics','皮肤科':'Dermatology','妇科':'Gynecology','五官科':'ENT & ophthalmology'})
D['kind']=D.user_type.map({'新用户':'New','老用户':'Returning'})
D['date']=pd.to_datetime(D.enter_date,format='mixed')
print('DAILY GAP')
daily=D.groupby(['date','arm']).first_response_seconds.median().unstack()
daily['gap']=daily.Control-daily.Treatment
print(daily.to_string())
print('\nDaily faster counts', (daily.Treatment<daily.Control).sum(), 'of',len(daily),'ties',(daily.Treatment==daily.Control).sum(),'gap median',daily.gap.median(),'min',daily.gap.min(),'max',daily.gap.max())
print('\nBY WEEK')
print(D.assign(week=D.date.dt.to_period('W').astype(str)).groupby(['week','arm']).agg(n=('user_id','size'),response=('first_response_seconds','median'),completion=('is_completed','mean'),loss=('lost_before_doctor','mean')).round(4).to_string())
print('\nWAIT THRESHOLDS')
for threshold in [60,120,180,300]:
 print(threshold,D.groupby('arm').first_response_seconds.apply(lambda s:100*(s<=threshold).mean()).round(2).to_dict())
print('\nCONSULT')
print(D.groupby('arm').consult_minutes.agg(['count','mean','median',lambda s:s.quantile(.9),lambda s:s.quantile(.95),'max']).round(2).to_string())
print('\nCOMPLAINT OVERALL TOP LOSS')
co=D.groupby(['dept','chief_complaint']).agg(n=('user_id','size'),loss=('lost_before_doctor','mean'),complete=('is_completed','mean'),response=('first_response_seconds','median'),followup=('followup_7d','mean')).sort_values('loss',ascending=False)
print(co.round(4).to_string())
print('\nCOMPLAINT BY ARM LOSS')
cp=D.groupby(['dept','chief_complaint','arm']).agg(n=('user_id','size'),loss=('lost_before_doctor','mean'),complete=('is_completed','mean'),response=('first_response_seconds','median')).round(4)
print(cp.loc['Dermatology'].to_string())
print('\nMISSING PATTERNS')
print(D.isna().sum().to_string())
print('first response missing equals lost', (D.first_response_seconds.isna()==D.lost_before_doctor.astype(bool)).all())
print('consult missing equals not completed', (D.consult_minutes.isna()==(D.is_completed==0)).all())
print('\nFOLLOWUP USER TYPE')
print(D.groupby(['kind','arm']).followup_7d.agg(n='count',rate='mean').round(5).to_string())
print('\nCI PRIMARY')
for val in ['lost_before_doctor','is_completed','followup_7d']:
 g=D.groupby('arm')[val].agg(['count','mean'])
 for arm in ['Control','Treatment']:
  n=g.loc[arm,'count']; p=g.loc[arm,'mean']; se=np.sqrt(p*(1-p)/n)
  print(val,arm,n,p,'CI',p-1.96*se,p+1.96*se)
